#!/usr/bin/env bash
# Kafka entrypoint: renders server.properties from KAFKA_* environment variables, formats the
# log directories on first start, then execs kafka-server-start.sh so signals reach the JVM.
#
# KAFKA_FOO_BAR=x becomes foo.bar=x, as in the apache/kafka image: "_" -> ".", "__" -> "_",
# "___" -> "-". Without KAFKA_PROCESS_ROLES the defaults below make a single combined
# broker+controller node; with it, the environment describes the node and only KAFKA_LOG_DIRS
# is defaulted. CLUSTER_ID is used on first start, or generated when unset; after that it lives
# in meta.properties in the log directories, and a different CLUSTER_ID is refused.
set -euo pipefail

config=/etc/kafka/server.properties

log() { echo "kafka-entrypoint: $*" >&2; }

# A first argument that is not an option for kafka-server-start.sh runs as a command instead.
if [[ $# -gt 0 && $1 != -* ]]; then
  exec "$@"
fi

default() {
  if [[ -z ${!1:-} ]]; then
    export "$1=$2"
  fi
}

if [[ -z ${KAFKA_PROCESS_ROLES:-} ]]; then
  export KAFKA_PROCESS_ROLES=broker,controller
  default KAFKA_NODE_ID 1
  default KAFKA_LISTENERS PLAINTEXT://:9092,CONTROLLER://:9093
  default KAFKA_ADVERTISED_LISTENERS PLAINTEXT://localhost:9092
  default KAFKA_LISTENER_SECURITY_PROTOCOL_MAP CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT
  default KAFKA_CONTROLLER_LISTENER_NAMES CONTROLLER
  default KAFKA_INTER_BROKER_LISTENER_NAME PLAINTEXT
  default KAFKA_CONTROLLER_QUORUM_VOTERS "${KAFKA_NODE_ID}@localhost:9093"
  default KAFKA_OFFSETS_TOPIC_REPLICATION_FACTOR 1
  default KAFKA_TRANSACTION_STATE_LOG_REPLICATION_FACTOR 1
  default KAFKA_TRANSACTION_STATE_LOG_MIN_ISR 1
  default KAFKA_SHARE_COORDINATOR_STATE_TOPIC_REPLICATION_FACTOR 1
  default KAFKA_SHARE_COORDINATOR_STATE_TOPIC_MIN_ISR 1
fi
default KAFKA_LOG_DIRS /var/lib/kafka/data

# Read by the Kafka scripts and the JVM, not server properties; the list is apache/kafka's,
# plus KAFKA_DEBUG.
excluded=" KAFKA_VERSION KAFKA_HEAP_OPTS KAFKA_LOG4J_OPTS KAFKA_OPTS KAFKA_JMX_OPTS
  KAFKA_JVM_PERFORMANCE_OPTS KAFKA_GC_LOG_OPTS KAFKA_LOG4J_ROOT_LOGLEVEL KAFKA_LOG4J_LOGGERS
  KAFKA_TOOLS_LOG4J_LOGLEVEL KAFKA_JMX_HOSTNAME KAFKA_DEBUG "

{
  echo "# Generated by kafka-entrypoint from KAFKA_* environment variables; rewritten on every start."
  while IFS= read -r name; do
    if [[ $excluded == *[[:space:]]"$name"[[:space:]]* ]]; then
      continue
    fi
    key=${name#KAFKA_}
    key=${key,,}
    key=${key//_/.}
    key=${key//.../-}
    key=${key//../_}
    printf '%s=%s\n' "$key" "${!name}"
  done < <(compgen -e -X '!KAFKA_*' | sort)
} >"$config"

IFS=, read -ra dirs <<<"$KAFKA_LOG_DIRS"
if [[ -n ${KAFKA_METADATA_LOG_DIR:-} ]]; then
  dirs+=("$KAFKA_METADATA_LOG_DIR")
fi

formatted_id=""
unformatted=false
for dir in "${dirs[@]}"; do
  if [[ -f $dir/meta.properties ]]; then
    formatted_id=${formatted_id:-$(sed -n 's/^cluster\.id=//p' "$dir/meta.properties")}
  else
    unformatted=true
  fi
done

if [[ -n $formatted_id ]]; then
  if [[ -n ${CLUSTER_ID:-} && $CLUSTER_ID != "$formatted_id" ]]; then
    log "CLUSTER_ID=$CLUSTER_ID, but the log directories belong to cluster $formatted_id"
    exit 1
  fi
  CLUSTER_ID=$formatted_id
elif [[ -z ${CLUSTER_ID:-} ]]; then
  CLUSTER_ID=$(kafka-storage.sh random-uuid)
  log "CLUSTER_ID not set; generated $CLUSTER_ID"
fi

if [[ $unformatted == true ]]; then
  log "formatting ${dirs[*]} for cluster $CLUSTER_ID"
  kafka-storage.sh format --config "$config" --cluster-id "$CLUSTER_ID" --ignore-formatted
else
  log "log directories already formatted for cluster $CLUSTER_ID"
fi

exec kafka-server-start.sh "$config" "$@"
